const LangCtx = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('lang') || 'zh')
  const setLangP = useCallback((l) => { setLang(l); localStorage.setItem('lang', l) }, [])
  const t = useCallback((k) => (DICT[lang] && DICT[lang][k]) || DICT.en[k] || k, [lang])
  return <LangCtx.Provider value={{ lang, setLang: setLangP, t }}>{children}</LangCtx.Provider>
}

export function useLang() {
  const ctx = useContext(LangCtx)
  if (!ctx) throw new Error('useLang must be used within LangProvider')
  return ctx
}
